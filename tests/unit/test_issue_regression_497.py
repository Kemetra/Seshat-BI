def _migration_ddl_columns() -> list[str]:
    """The reference star's date-dimension columns, read from the committed DDL."""
    ddl = next(_REPO.glob("warehouse/migrations/0004_*.sql")).read_text(
        encoding="utf-8"
    )
    block = re.search(
        r"create table\s+gold\.dim_date_rss\s*\((.*?)\);",
        ddl,
        re.IGNORECASE | re.DOTALL,
    )
    assert block, "could not locate the reference date-dimension DDL"
    return [
        m.group(1)
        for line in block.group(1).splitlines()
        if (m := re.match(r"\s*([a-z_][a-z0-9_]*)\s+[A-Za-z]", line))
    ]


