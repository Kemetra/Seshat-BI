# ---------------------------------------------------------------------------
# THE core guard: both consumers resolve the SAME set from the SAME input
# ---------------------------------------------------------------------------
#
# This is the regression guard for the amended ruling. #497 is a
# two-declarations bug, so the invariant is not "the builder is right" but "the
# builder and the reader cannot disagree". `gap_detector` decides which columns a
# star makes AVAILABLE (and can false-block an APPROVED metric contract -- #491);
# `model_plan` decides which columns get BUILT. If those drift, the tool reports a
# column present that no build path produces.


def _reader_calendar_columns(date_dimension: dict) -> set[str]:
    """The calendar attributes `gap_detector` believes the star exposes.

    Isolated by DIFFERENCE against the same star with no date dimension, so only
    tokens the date path contributes are compared -- never the fact's measures or an
    entity dim's attributes, which `_collect_gold` also harvests.
    """
    from seshat.gap_detector import _collect_gold

    def tokens(date_dim: dict | None) -> set[str]:
        star: dict = {
            "fact": {"name": "gold.fct_orders", "measures": ["net_sales"]},
            "dimensions": [],
        }
        if date_dim is not None:
            star["date_dimension"] = date_dim
        _, cols = _collect_gold({"gold_star": star})
        return cols

    contributed = tokens(date_dimension) - tokens(None)
    return contributed - {date_dimension.get("surrogate_key")}


def _builder_calendar_columns(date_dimension: dict) -> set[str]:
    """The calendar attributes the dbt scaffolder actually BUILDS."""
    surrogate = date_dimension.get("surrogate_key")
    return {c.name for c in _date_model(date_dimension).columns if c.name != surrogate}


@pytest.mark.parametrize(
    "attributes",
    [
        None,  # the absent-case default -- governs every tracked map
        ["full_date", "year"],  # a NARROWED calendar
        ["full_date"],  # the narrowest useful calendar
        ["year", "full_date"],  # declared out of DDL order
    ],
    ids=["defaulted", "narrowed", "minimal", "reordered"],
)
def test_the_builder_and_the_reader_resolve_the_same_calendar(
    attributes: list[str] | None,
) -> None:
    """Cross-surface agreement. Pre-fix the builder used a private 6-entry
    `_DATE_COLUMNS` while the reader used the 9-entry RC15 set, so they disagreed
    even in the DEFAULT case; and honoring `attributes` in only one of them would
    have made every narrowed calendar disagree too."""
    date_dimension = dict(_DEFAULTED)
    if attributes is not None:
        date_dimension["attributes"] = attributes

    builder = _builder_calendar_columns(date_dimension)
    reader = _reader_calendar_columns(date_dimension)

    assert builder == reader, (
        "the dbt builder and the gap_detector reader disagree about the calendar: "
        f"built-but-not-reported={sorted(builder - reader)} "
        f"reported-but-not-built={sorted(reader - builder)}"
    )


def test_the_reader_never_claims_a_column_the_builder_does_not_build() -> None:
    """The dangerous direction, stated on its own: a column reported AVAILABLE that
    no build path produces lets a metric contract bind to something that will not
    exist in the warehouse."""
    date_dimension = {**_DEFAULTED, "attributes": ["full_date", "year"]}

    phantom = _reader_calendar_columns(date_dimension) - _builder_calendar_columns(
        date_dimension
    )

    assert phantom == set(), f"reported available but never built: {sorted(phantom)}"


def test_neither_consumer_keeps_a_private_calendar_list() -> None:
    """The deduplication IS the fix. Both modules must route through the shared
    resolver, and neither may REDEFINE the calendar set.

    Checked by module attribute, not by source string: asserting a name like
    `iso_week` is absent from the source would break the moment any docstring in
    either module explains the calendar (this repo has hit that docstring-prose
    duplication trap before), and a comment naming a column is not a second
    declaration.
    """
    import inspect

    from seshat import gap_detector, star_discovery

    # The old private tuple is gone, and no equivalent is re-exported.
    assert not hasattr(model_plan, "_DATE_COLUMNS")
    for module in (model_plan, gap_detector):
        source = inspect.getsource(module)
        assert "resolve_date_attributes" in source, (
            f"{module.__name__} does not consume the shared resolver"
        )
        # No consumer may bind its own copy of the calendar set under ANY name: a
        # module-level collection of calendar names is the defect coming back.
        for name, value in vars(module).items():
            if isinstance(value, (tuple, frozenset, set, list)) and value:
                overlap = {v for v in value if isinstance(v, str)} & set(
                    star_discovery.RC15_CALENDAR_COLUMNS
                )
                assert not overlap, (
                    f"{module.__name__}.{name} holds calendar column names "
                    f"{sorted(overlap)}; the set belongs to star_discovery alone"
                )

    # star_discovery is the single declaration site.
    assert star_discovery.RC15_CALENDAR_COLUMNS


