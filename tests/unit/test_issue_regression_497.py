"""Regression tests for issue #497 (the dbt scaffolder built a divergent calendar).

`dbt/scaffold/model_plan.py` hardcoded

    _DATE_COLUMNS = ("full_date", "year", "quarter", "month", "day", "iso_week")

and `_date_dimension` built `(surrogate, *_DATE_COLUMNS)` while NEVER reading
`attributes` -- unlike `_dimension_model`, which reads them for every explicit
dimension. So every scaffolded date dimension got those six columns regardless of
the approved map, and it disagreed with `warehouse/migrations/0004_*.sql`
(gold.dim_date_rss), which carries `month_name`, `day_name` and `is_weekend` too.
The same approved map therefore produced a STRUCTURALLY DIFFERENT date dimension
on the two build paths, and nothing detected it: the parity audit compares values
only (that is #492) and a calendar's member count matches whether or not
`month_name` exists.

Resolution (owner-ruled R6, as amended): ONE SHARED RESOLVER,
`star_discovery.resolve_date_attributes`, consumed by BOTH the builder
(`dbt/scaffold/model_plan`) and the reader (`gap_detector`). `_DATE_COLUMNS` is
DELETED rather than corrected -- a second hardcoded tuple IS the defect #497
reports, so neither consumer may keep a private list. The deduplication is the part
that actually closes the issue.

DEFAULT WHEN `attributes` IS ABSENT: the full RC15 calendar, which equals the
migrations DDL set. Since ZERO tracked maps declare `date_dimension.attributes`,
that default governs EVERY existing map: any other default would relocate the
divergence instead of removing it.

The prior #491 ruling STANDS and is not overturned. It forbade honoring
`date_dimension.attributes` in ONE consumer, because a lone reader honoring it
while the builder ignored it manufactures a fresh cross-surface disagreement (the
#487 defect). Honoring it in the SHARED resolver is the opposite move: it keeps the
two surfaces in lockstep, so a narrowed calendar narrows both. RC15 remains the
authority for what a calendar CONTAINS; `attributes` selects from it and can never
introduce a column (a calendar is generated by generate_series, so an off-contract
attribute has no source column to derive from and is rejected).

`tests/unit/test_issue_regression_491.py` passes UNMODIFIED under this change --
its ruling docstring needed no edit.

NOT covered here: asserting the two build paths' column sets match inside the
parity audit. That is #492, deliberately scoped to value-only by ratified
ADR-0009.
"""

